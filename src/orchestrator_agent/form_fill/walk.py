"""The walk over core's form: from page 0, each page submitted as it is known, until a stop.

Core is the only judge of a page: what is missing and what is wrong come back in its words, in one stop.
What a page's schema alone decides is said here before anything is submitted (``PAGE_CHECKS``, in order).
Re-walking from page 0 every turn is what makes corrections free (pages after a changed answer are
regenerated by core) and keeps the session tiny; each page costs one MCP call. A walk ends in exactly one
of three ways: a page's questions (a ``Reply`` with its stop), the form ``Completed`` (every page validated
and committed to the session, the start to be approved), or a close with its reason (a failed ``Reply``).
The validated pages are committed only when the walk stops, so a failure in the middle leaves the session
as it was.
"""

from __future__ import annotations

from collections.abc import Callable, Mapping, Sequence
from dataclasses import dataclass
from typing import Any, Literal, Protocol

import structlog
from orchestrator.core.schemas.mcp_tools import GetWorkflowFormRequest, WorkflowFormPage
from pydantic_ai import ModelRetry
from pydantic_forms.core import FormFieldError

from orchestrator_agent.form_fill import session as fs
from orchestrator_agent.form_fill.interpret import Chooser, Interpreter
from orchestrator_agent.form_fill.model import ACCEPT, FieldSpec, askable, fields_of, form_schema, label_of, options_of
from orchestrator_agent.form_fill.questions import offered, questions
from orchestrator_agent.form_fill.verdicts import miscounted, picked, unanswerable
from orchestrator_agent.form_fill.widgets import Fetch, FieldWidget, WidgetContext
from orchestrator_agent.form_fill.widgets.enrich import EnrichedPage, LongList, enrich
from orchestrator_agent.form_fill.widgets.resolve import Resolution, resolve_answer, shown_as
from orchestrator_agent.form_fill.widgets.waiting import takes_only_option, waiting, waits
from orchestrator_agent.state import Approval, AskField, FormFillSession, FormReply, Reply
from orchestrator_agent.tool_names import GET_WORKFLOW_FORM_TOOL

logger = structlog.get_logger(__name__)

_MAX_PAGES = 50  # a form that keeps producing pages is broken, not long


class CallTool(Protocol):
    """Call one of core's MCP tools by name (bound to an open MCP session by the adapter)."""

    async def __call__(self, name: str, args: dict[str, Any]) -> Any: ...


@dataclass(frozen=True)
class Walk:
    """One walk's collaborators: the session walked, core's tools, and the widgets and models its pages may need."""

    session: FormFillSession
    call_tool: CallTool
    widgets: Sequence[FieldWidget] = ()  # the fields whose options core leaves to a client
    fetch: Fetch | None = None  # core's API, where a field's source is fetched from
    choose: Chooser | None = None  # words a person typed for a widget field -> the options they fit
    interpret: Interpreter | None = None  # a person's answers core rejected -> the values the fields expect


@dataclass(frozen=True)
class Completed:
    """The walk reached the end: every page validated and committed; the start is to be approved."""


@dataclass(frozen=True)
class Seen:
    """A page as the walk sees it after enrichment: its askable fields, what is known for them, what resolving said."""

    page: WorkflowFormPage
    pages: list[dict[str, Any]]  # the validated pages before it
    fields: Sequence[FieldSpec]
    values: dict[str, Any]  # what would be submitted for it
    unresolved: Mapping[str, Resolution]  # widget fields whose words resolved to no option
    choices: Mapping[str, LongList]  # the page's widget fields with their options


PageCheck = Callable[[Walk, Seen], Reply | None]


def as_reply(data: FormReply, *, ask: Sequence[AskField] | None = None, approval: Approval | None = None) -> Reply:
    return Reply(data.as_text(), ask=ask, approval=approval)


def reply_of(session: FormFillSession, status: Any, **data: Any) -> Reply:
    return as_reply(FormReply(workflow_key=session.workflow_key, status=status, **data))


async def _no_fetch(url: str) -> Any:
    raise RuntimeError("no API of core is configured to fetch a field's options from")


# --- the walk ---------------------------------------------------------------------------------------------------


async def page_of(ctx: Walk, pages: list[dict[str, Any]]) -> WorkflowFormPage:
    """Core's verdict on ``pages``: the next page, the form complete, or the page it rejected with its errors."""
    request = GetWorkflowFormRequest(workflow_key=ctx.session.workflow_key, page_inputs=pages, verdict="result")
    return WorkflowFormPage.model_validate(await ctx.call_tool(GET_WORKFLOW_FORM_TOOL, request.model_dump()))


async def walk(ctx: Walk) -> Reply | Completed:
    """Walk from page 0, submitting each page as it is known; stop where core does not accept one, or at the end.

    A page core rejected is read once by the interpreter where a person typed something, and walked again
    from page 0 when that changed a value; otherwise its fields are the questions, with core's message on
    the ones it rejected. A page core describes is checked (``PAGE_CHECKS``) before it is submitted.
    """
    session = ctx.session
    pages: list[dict[str, Any]] = []
    interpreted: set[str] = set()
    fs.begin_walk(session)
    while len(pages) < _MAX_PAGES:
        try:
            page = await page_of(ctx, pages)
        except ModelRetry as exc:  # no verdict on a page: core refuses the workflow itself, or is in trouble
            if not pages:  # nothing was submitted: core does not know the workflow, and the form closes
                fs.close(session)
                return reply_of(session, "failed", reason=str(exc))
            return page_stop(ctx, session.pages[-1], pages, reason=str(exc))  # asked again, with it
        if page.status == "rejected":  # values missing or wrong: the human's to fix, after one reading
            page = as_walked(session, page)
            if await reinterpret(ctx, page.errors, interpreted):
                pages = []  # values changed: walk again from page 0
                fs.begin_walk(session)
                continue
            return page_stop(ctx, page, pages, page.errors)
        if page.complete:
            stop(session, pages, "confirming")
            return Completed()
        enriched_page, unresolved = await enriched(ctx, pages, page.schema_ or {})
        page = page.model_copy(update={"schema_": enriched_page.schema})
        fs.saw_page(session, page)
        fields = [field for field in fields_of(page) if askable(field)]
        seen = Seen(page, pages, fields, see_page(session, fields, pages), unresolved, enriched_page.choices)
        if decided := next(filter(None, (check(ctx, seen) for check in PAGE_CHECKS)), None):
            return decided
        pages.append(seen.values)
    fs.close(session)
    return reply_of(session, "failed", reason=f"the form did not complete after {_MAX_PAGES} pages")


# --- what a page settles before it is submitted, in this order ------------------------------------------------


def _unanswerable(ctx: Walk, seen: Seen) -> Reply | None:
    """A page no answer can satisfy (its schema says so) closes the form with the reason."""
    if reason := unanswerable(seen.fields):
        fs.close(ctx.session)
        return reply_of(ctx.session, "failed", reason=reason)
    return None


def _miscounted(ctx: Walk, seen: Seen) -> Reply | None:
    """A list answered with the wrong number of items is asked again with the count."""
    if wrong := miscounted(seen.fields, seen.values):
        return page_stop(ctx, seen.page, [*seen.pages, seen.values], wrong)
    return None


def _unresolved(ctx: Walk, seen: Seen) -> Reply | None:
    """Words that are no option: the page is asked again (with what they matched), never submitted with them."""
    if not seen.unresolved:
        return None
    asked = {name: value for name, value in seen.values.items() if name not in seen.unresolved}
    return offered(page_stop(ctx, seen.page, [*seen.pages, asked]), seen.unresolved)


def _untouched(ctx: Walk, seen: Seen) -> Reply | None:
    """A page of optional fields nobody has said anything about is asked once; so is a field that has its options now.

    Whatever the caller replies to the optional page, defaults then apply (a modify-note page is only its
    optional note). A field that waited for another value at the last stop is offered once it has options.
    """
    session = ctx.session
    untouched = not seen.values and seen.fields and not any(field.required for field in seen.fields)
    offers = any(name in session.waiting and name not in seen.values for name in seen.choices)
    if offers or (untouched and not any(field.name in session.asked for field in seen.fields)):
        return page_stop(ctx, seen.page, [*seen.pages, seen.values])
    return None


PAGE_CHECKS: tuple[PageCheck, ...] = (_unanswerable, _miscounted, _unresolved, _untouched)


# --- a page's widgets: enriched, resolved -----------------------------------------------------------------------


async def enriched(
    ctx: Walk, pages: list[dict[str, Any]], schema: dict[str, Any]
) -> tuple[EnrichedPage, dict[str, Resolution]]:
    """The page with its widgets' options, its answered widget fields resolved; those that were not, by name.

    A widget reads the values known so far, so once resolving changed what it read — a typed name became
    its option, which another field's source depends on — the page is enriched and resolved once more (and only once).
    """
    wctx = widget_context(ctx, pages)
    page = await enrich(schema, ctx.widgets, wctx)
    unresolved = await resolve(ctx, page.choices, wctx)
    resolved = widget_context(ctx, pages)
    if resolved.values == wctx.values:
        return page, unresolved
    page = await enrich(schema, ctx.widgets, resolved)
    return page, {**unresolved, **await resolve(ctx, page.choices, resolved)}


def widget_context(ctx: Walk, pages: list[dict[str, Any]]) -> WidgetContext:
    """What a widget may use on this page: core's tools and API, and every value known so far."""
    known = {name: value for page in pages for name, value in page.items()}
    return WidgetContext(call_tool=ctx.call_tool, fetch=ctx.fetch or _no_fetch, values={**known, **ctx.session.values})


async def resolve(ctx: Walk, widget_choices: Mapping[str, LongList], wctx: WidgetContext) -> dict[str, Resolution]:
    """Each answered widget field of the page resolved to its options in place; those that were not, by name.

    Every widget field with options is resolved, chips included: core takes any string for some of them
    (a sourced field is a plain string to it), and a transport takes typed text next to the chips. A picked
    chip is one of the options and stands without a model call. A resolved value replaces the words, so the
    next walk finds it among the options and reads nothing again.
    """
    session = ctx.session
    answered = {
        name: choice for name, choice in widget_choices.items() if session.values.get(name) not in (None, "", [])
    }
    outcomes = {
        name: await resolve_answer(choice, session.values[name], wctx, ctx.choose) for name, choice in answered.items()
    }
    for name, outcome in outcomes.items():
        record(session, name, widget_choices[name], outcome)
    return {name: outcome for name, outcome in outcomes.items() if not outcome.resolved}


def record(session: FormFillSession, name: str, choice: LongList, outcome: Resolution) -> None:
    """Keep what the words resolved to in place of the words; drop words that did not resolve (core never sees them)."""
    if outcome.resolved:
        fs.keep_resolved(session, name, outcome.value, shown_as(choice, outcome.value))
    else:
        fs.drop_answer(session, name)


# --- a stop, and what a page is submitted with --------------------------------------------------------------


def page_stop(
    ctx: Walk,
    page: WorkflowFormPage,
    pages: list[dict[str, Any]],
    errors: Sequence[FormFieldError] = (),
    reason: str | None = None,
) -> Reply:
    """The stop at ``page``, the last of ``pages``: its fields as questions, with core's verdict on it.

    The pages before it are the validated ones; the fields it asks count as asked. ``reason`` is a refusal that
    is no form verdict: the page is asked again with it, so a passing failure costs the human one
    answer, not the form. Only a stop with nothing to ask — a page without a field — closes the form.
    """
    session = ctx.session
    fields = fields_of(page)
    stop(session, pages[:-1], "gathering")
    rejected = {str(error.loc[0]) for error in errors if error.loc}
    values = {**fs.given(session), **{name: value for name, value in pages[-1].items() if name not in rejected}}
    ask = questions(fields, values, errors, reason, asked=session.asked)
    fs.mark_asked(session, [asked.name for asked in ask])
    if not ask:
        fs.close(session)
        return reply_of(session, "failed", reason=reason or "the form asks for nothing a person can answer")
    data = FormReply(
        workflow_key=session.workflow_key,
        status="gathering",
        page=page.page,
        title=page.title,
        rejected=list(errors),
        reason=reason,
        values=values,
        labels=labels(session, values),
    )
    return as_reply(data, ask=ask)


async def reinterpret(ctx: Walk, errors: Sequence[FormFieldError], done: set[str]) -> bool:
    """Where core rejected a person's answers, ask the interpreter for the values — one call per page, once per answer.

    This runs for what a person typed: a number in words, an option described, a structured field. An
    answer made of the field's own option values is picks, and stands as picked (core's verdict on it is
    shown). A widget field is not read here: its words were resolved to an option before the page was
    submitted. True when any value changed (the walk starts over).
    """
    session = ctx.session
    if ctx.interpret is None:
        return False
    form = form_schema(session.pages)
    fields = fs.fields(session)
    words: dict[str, str] = {}
    for error in errors:
        name = str(error.loc[0]) if error.loc else ""
        raw = session.values.get(name)
        widget = name in fields and fields[name].widget is not None
        is_picked = name in fields and picked(fields[name], raw)
        if name not in form["properties"] or widget or is_picked or name in done or raw is None:
            continue
        done.add(name)
        answer = raw if isinstance(raw, str) else str(raw)
        if session.interpreted.get(name) != answer:  # the same words again: what was made of them stands
            fs.interpret_words(session, name, answer)
            words[name] = answer
    if not words:
        return False
    values = await ctx.interpret.answers(form, words)
    fs.answer(session, values)
    return bool(values)


def stop(session: FormFillSession, pages: list[dict[str, Any]], status: Literal["gathering", "confirming"]) -> None:
    """The walk stopped after ``pages``, the validated ones; the widget fields still waiting are remembered."""
    fs.stop_at(session, pages, status, waiting(session.pages))


def see_page(session: FormFillSession, fields: Sequence[FieldSpec], pages: list[dict[str, Any]]) -> dict[str, Any]:
    """Collect what is known for the fields of the page after ``pages``: the caller's values, the obvious.

    A value goes to core exactly as sent; nothing here judges it. A required choice of the form's own with
    exactly one option is taken without asking anyone (as the one-item list a single-select list wants),
    each walk anew: the options of a regenerated page may differ. A widget field's only option is never
    taken: its options are what the network has now (one free port), and choosing it is the person's. A
    widget field still waiting for its options sends nothing: no value of it is one of its options yet.
    Consent (``Accept``) counts for what it was given for — see ``consented``.
    """
    values: dict[str, Any] = {}
    accepts: list[FieldSpec] = []
    for field in fields:
        options = options_of(field) or []
        if field.format == ACCEPT:
            accepts.append(field)
        elif field.name in session.values and not waits(field):
            values[field.name] = session.values[field.name]
        elif takes_only_option(field) and len(options) == 1:
            (only,) = options
            values[field.name] = [only.value] if field.kind == "list" else only.value
    if accepts:
        seen = fs.fingerprint([*pages, values])
        for field in accepts:
            accepted = next((option.value for option in options_of(field) or []), None)
            if consented(session, field.name, accepted, page_index=len(pages), seen=seen):
                values[field.name] = accepted
    return values


def consented(session: FormFillSession, name: str, accepted: Any, *, page_index: int, seen: str) -> bool:
    """Whether this page has the caller's consent for this field, given for what it shows now (``seen``).

    Consent is kept per page and field, with the fingerprint of the pages before it and the rest of its
    own: it holds through a re-walk that changes none of that, and is void once a correction does. A
    fresh consent is for the page being asked now and is consumed by it, never carried to a later page
    that asks the same thing.
    """
    key = f"{page_index}:{name}"
    if session.consents.get(key) == seen:
        return True
    if accepted is not None and session.values.get(name) == accepted:
        fs.consent(session, key, seen, name)
        return True
    return False


def labels(session: FormFillSession, values: Mapping[str, Any]) -> dict[str, Any]:
    """How the form shows each of ``values`` that is one of its field's options (an id says nothing to a person)."""
    fields = fs.fields(session)
    shown = {name: label_of(fields[name], value) for name, value in values.items() if name in fields}
    resolved = {
        name: kept["label"]
        for name, kept in session.resolved.items()
        if name in values and values[name] == kept["value"]
    }
    return {**resolved, **{name: label for name, label in shown.items() if label is not None}}


def as_walked(session: FormFillSession, page: WorkflowFormPage) -> WorkflowFormPage:
    """A rejected page as it was walked: with the options its widgets wrote in when it was first seen."""
    walked = next((seen for seen in session.pages if seen.page == page.page), None)
    return page if walked is None else page.model_copy(update={"schema_": walked.schema_})


