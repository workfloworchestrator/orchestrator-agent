"""The workflow form-fill skill: deterministic and LLM-free.

Over A2A the caller is another agent, so nothing here needs to *write* language: code walks the
multi-page form via core's MCP tools and every answer is one JSON object (``FormReply``) carrying core's
own data — the page's schema, what core rejected in its own words, the values so far, the process
started. *Which* workflow a request asks for is the model's call: it hands off with the
``start_workflow_form`` tool (``handoff``, which checks the key against core's catalogue) and ``open``
walks the first pages in the same turn. Everything after that is data or the interpreter's reading of it:
a message that is a JSON object of values is taken as sent, any other message is read by the
``Interpreter`` (a model) against the current stop for values and, when stated outright, a decision.
No word is matched by this code. Core's own
validation is the only validation. One skill turn is one caller message:

- opening (just handed off): the values the request states are taken, with the subscription the model
  passed on, and the form is **walked** from page 0; a subscription core will not run the workflow on is
  rejected by core's own subscription page, like any other value.
- gathering: the values the message states are recorded, then the form is walked again from page 0,
  each page submitted to core as it is known; the walk stops at the first page core does not accept —
  its verdict is the reply — or at the summary. Where core rejects a person's words, an ``Interpreter``
  turns them into values once, then core decides again.
- confirming: corrections re-walk; a start decision starts (``create_workflow`` with exactly the last walk's
  validated pages), a cancel decision cancels — never a start next to changed values.

Re-walking from page 0 every turn is what makes corrections free (pages after a changed answer are
regenerated by core) and keeps the session tiny; each page costs one MCP call. Routing by a typed decision
engine in front of the model, and prefilling pages from the conversation, live on the Jev branch.
"""

from __future__ import annotations

import time
from collections.abc import Mapping
from dataclasses import dataclass
from dataclasses import field as dc_field
from typing import Any, Literal, Protocol

import structlog
from orchestrator.core.schemas.mcp_tools import GetWorkflowFormRequest, ListWorkflowsRequest, WorkflowFormPage
from orchestrator.core.schemas.process import ProcessIdSchema
from orchestrator.core.schemas.workflow import WorkflowSchema
from pydantic import BaseModel, TypeAdapter
from pydantic_ai import ModelRetry

from orchestrator_agent.form_fill.core_bridge import (
    choices,
    form_errors,
    form_model,
    is_accept,
    is_list,
    is_single_pick,
    page_model,
)
from orchestrator_agent.form_fill.interpret import Interpreter
from orchestrator_agent.state import (
    ACCEPT_VALUE,
    SUBSCRIPTION_ID,
    Decision,
    FormFillSession,
    FormReply,
    Reply,
    SearchState,
    values_in,
)
from orchestrator_agent.tool_names import (
    CREATE_WORKFLOW_TOOL,
    GET_WORKFLOW_FORM_TOOL,
    JSON_DATA_PARAM,
    LIST_WORKFLOWS_TOOL,
    WORKFLOW_KEY_PARAM,
)

logger = structlog.get_logger(__name__)

# Core's tool results are validated with core's own response models (the agent depends on orchestrator-core),
# and its tool arguments are built from core's request models — nothing here spells out a field of either.
_WORKFLOW_LIST: TypeAdapter[list[WorkflowSchema]] = TypeAdapter(list[WorkflowSchema])

TRUE, FALSE = "true", "false"  # a boolean field's chips; pydantic reads them back


class CallTool(Protocol):
    """Call one of core's MCP tools by name (bound to an open MCP session by the adapter)."""

    async def __call__(self, name: str, args: dict[str, Any]) -> Any: ...


_MAX_PAGES = 50  # a form that keeps producing pages is broken, not long
_WORKFLOWS_TTL = 300.0  # seconds the workflow catalogue is cached per skill instance


def as_reply(data: FormReply) -> Reply:
    return Reply(data.as_text())


@dataclass
class FormFillSkill:
    interpret: Interpreter | None = None  # a person's answers core rejected -> the values the fields expect
    _catalogue: dict[str, str] | None = dc_field(default=None, init=False, repr=False)
    _catalogue_at: float = dc_field(default=0.0, init=False, repr=False)

    @staticmethod
    def wants(state: SearchState) -> bool:
        """Whether this message can be the skill's at all: a form is open."""
        return state.form_fill is not None

    async def handle(self, text: str, state: SearchState, call_tool: CallTool) -> Reply | None:
        """Handle one caller message; the reply, or None when this is not a form-fill message."""
        session = state.form_fill
        if session is None:
            return None  # routing is the model's, via the handoff tool
        if session.status == "opening":
            state.form_fill = None  # a handoff that was never walked (the turn failed): start over
            return None
        values, decision = values_in(text), None
        if values is None and self.interpret is not None:  # not the data model: read it against the current stop
            confirming = session.status == "confirming"
            allowed = [Decision.CANCEL, Decision.START] if confirming else [Decision.CANCEL]
            # At the summary anything may be corrected; at a page the words answer that page, so fields of other
            # pages are not offered (a number inside a note is not a version).
            stop = form_model(session.pages) if confirming or not session.pages else page_model(session.pages[-1])
            asked = (
                f"workflow `{session.workflow_key}`: every value to be submitted was shown and the person was asked "
                "to confirm the start"
                if confirming
                else f"workflow `{session.workflow_key}`: the person was asked for the values of the current page "
                "(the fields given)"
            )
            read = await self.interpret.message(stop, text, allowed, asked)
            values, decision = read.values or None, read.decision
        return self._finish(state, session, await self._turn(session, values, decision, call_tool))

    async def open(self, state: SearchState, call_tool: CallTool) -> Reply | None:
        """Walk the form the model handed off (``start_workflow_form``); None if there is none.

        The opening message is the caller's request: values it states (a JSON object) are taken; the
        subscription the model passed on fills the form's first page, and core's verdict on it is the
        reply like any other. So is core's refusal of the workflow itself (a key the handoff tool checked
        but core no longer knows): the form closes with it.
        """
        session = state.form_fill
        if session is None or session.status != "opening":
            return None
        logger.info(
            "Form-fill opened by the model",
            workflow=session.workflow_key,
            subscription_id=session.values.get(SUBSCRIPTION_ID),  # the model passes the one it knows with the handoff
        )
        session.status = "gathering"
        session.values.update(values_in(session.request) or {})  # a request that is data; words are the model's
        return self._finish(state, session, await self._walk(session, call_tool))

    # --- one turn ------------------------------------------------------------------------------------

    async def _turn(
        self, session: FormFillSession, values: Mapping[str, Any] | None, decision: Decision | None, call_tool: CallTool
    ) -> Reply:
        """What the message does: cancel; change values (the form is walked again); start, at the summary; or nothing.

        A start next to changed values is not a start: the values are walked and the new summary asks again.
        Nothing usable is answered with the same stop.
        """
        if decision is Decision.CANCEL:
            session.status = "done"
            return self._reply(session, "cancelled")
        if values:
            session.values.update(values)
            return await self._walk(session, call_tool)
        if decision is Decision.START and session.status == "confirming":
            return await self._start(session, call_tool)
        return await self._walk(session, call_tool)

    @staticmethod
    def _finish(state: SearchState, session: FormFillSession, reply: Reply) -> Reply:
        state.form_fill = None if session.status == "done" else session
        return reply

    @staticmethod
    def _reply(session: FormFillSession, status: Any, **data: Any) -> Reply:
        return as_reply(FormReply(workflow_key=session.workflow_key, status=status, **data))

    # --- core's catalogue ---------------------------------------------------

    async def workflows(self, call_tool: CallTool) -> dict[str, str]:
        """User-facing workflows as ``{key: description}``, cached briefly (the catalogue is static per deployment)."""
        now = time.monotonic()
        if self._catalogue is not None and now - self._catalogue_at < _WORKFLOWS_TTL:
            return self._catalogue
        listed = _WORKFLOW_LIST.validate_python(
            await call_tool(LIST_WORKFLOWS_TOOL, ListWorkflowsRequest(is_task=False).model_dump(exclude_none=True))
        )
        self._catalogue = {wf.name: wf.description or wf.name for wf in listed}
        self._catalogue_at = now
        return self._catalogue

    # --- the walk ----------------------------------------------------------------------------------

    async def _walk(self, session: FormFillSession, call_tool: CallTool) -> Reply:
        """Walk from page 0, submitting each page as it is known; stop where core does not accept one, or at the summary.

        Core is the only judge of a page: what is missing and what is wrong come back in its words, in one
        stop (gathering). A page of optional fields nobody has touched is asked once, since core would accept
        it as it is. The validated pages are committed to the session only when the walk stops, so a failure
        in the middle (an exception propagating to the adapter) leaves the session as it was.
        """
        pages: list[dict[str, Any]] = []
        interpreted: set[str] = set()
        session.pages = []  # this walk's pages only: a regenerated form leaves no stale field behind
        while len(pages) < _MAX_PAGES:
            try:
                page = WorkflowFormPage.model_validate(
                    await call_tool(
                        GET_WORKFLOW_FORM_TOOL,
                        GetWorkflowFormRequest(workflow_key=session.workflow_key, page_inputs=pages).model_dump(),
                    )
                )
            except ModelRetry as exc:  # core did not accept the last page: values missing or wrong
                if not pages:  # no page was submitted: core refuses the workflow itself, and the form closes
                    session.status = "done"
                    return self._reply(session, "failed", reason=str(exc))
                if await self._reinterpret(session, str(exc), interpreted):
                    pages, session.pages = [], []  # values changed: walk again from page 0
                    continue
                return self._page_stop(session, pages, str(exc))  # the caller's to fix
            if page.complete:
                self._stop(session, pages, "confirming")
                return self._summary(session)

            schema = page.schema_ or {}
            session.pages.append(schema)
            model = page_model(schema)
            values = self._see_page(session, model, page_index=len(pages))
            fields = model.model_fields
            # A page of optional fields nobody has said anything about is asked once (a modify-note page is
            # only its optional note); whatever the caller replies, defaults then apply.
            untouched = not values and fields and not any(f.is_required() for f in fields.values())
            if untouched and not any(name in session.asked for name in fields):
                return self._page_stop(session, [*pages, values])
            pages.append(values)
        session.status = "done"
        return self._reply(session, "failed", reason=f"the form did not complete after {_MAX_PAGES} pages")

    def _page_stop(self, session: FormFillSession, pages: list[dict[str, Any]], error: str | None = None) -> Reply:
        """The stop at the last of ``pages``: core's verdict on it (none when it was never submitted) goes back to the caller.

        The pages before it are the validated ones; its fields count as asked.
        """
        schema = session.pages[-1]
        model = page_model(schema)
        self._stop(session, pages[:-1], "gathering")
        session.asked.extend(name for name in model.model_fields if name not in session.asked)
        return self._gathering(session, model, pages[-1], error, page=len(pages) - 1, title=schema.get("title"))

    def _gathering(
        self,
        session: FormFillSession,
        model: type[BaseModel],
        submitted: Mapping[str, Any],
        error: str | None,
        *,
        page: int | None = None,
        title: str | None = None,
    ) -> Reply:
        """Core's verdict on ``submitted`` as the reply: its errors as they are, the model's schema, the values known so far."""
        errors = form_errors(error) if error else []
        reason = error if error and not errors else None  # a refusal that is not a form body, as it came
        rejected = {str(e["loc"][0]) for e in errors if e["loc"]}
        values = {name: value for page_values in session.page_inputs for name, value in page_values.items()}
        values.update({name: value for name, value in submitted.items() if name not in rejected})
        data = FormReply(
            workflow_key=session.workflow_key,
            status="gathering",
            page=page,
            title=title,
            schema_=model.model_json_schema(),
            rejected=errors,
            reason=reason,
            values=values,
        )
        return as_reply(data)

    async def _reinterpret(self, session: FormFillSession, error: str, done: set[str]) -> bool:
        """Where core rejected a person's answers, ask the interpreter for the values — one call per page, once per answer.

        A caller that is an agent sends the format the stop asked for, so this mostly never runs; through
        a chat client the answers are a person's words. True when any value changed (the walk starts over).
        """
        if self.interpret is None:
            return False
        form = form_model(session.pages)
        words: dict[str, str] = {}
        for problem in form_errors(error):
            name = str(problem["loc"][0]) if problem["loc"] else ""
            raw = session.values.get(name)
            if name not in form.model_fields or name in done or raw is None:
                continue
            done.add(name)
            answer = raw if isinstance(raw, str) else str(raw)
            if session.interpreted.get(name) != answer:  # the same words again: what was made of them stands
                session.interpreted[name] = answer
                words[name] = answer
        if not words:
            return False
        values = await self.interpret.answers(form, words)
        for name, value in values.items():
            session.values[name] = value
        return bool(values)

    @staticmethod
    def _stop(
        session: FormFillSession, pages: list[dict[str, Any]], status: Literal["gathering", "confirming"]
    ) -> None:
        session.page_inputs = pages
        session.status = status

    @staticmethod
    def _see_page(session: FormFillSession, model: type[BaseModel], *, page_index: int) -> dict[str, Any]:
        """Collect what is known for the page's fields: the caller's values, the obvious.

        A value goes to core exactly as sent; nothing here judges it. Consent (``Accept``) counts once, for
        the page it was given for, and is never carried to another page; a choice with exactly one option
        is taken without asking anyone (as the one-item list a single-select list wants).
        """
        values: dict[str, Any] = {}
        for name, info in model.model_fields.items():
            if is_accept(info):
                if FormFillSkill._consented(session, name, page_index):
                    values[name] = ACCEPT_VALUE
                continue
            if name in session.values:
                values[name] = session.values[name]
            elif is_single_pick(info) and len(options := choices(info) or ()) == 1:
                (only,) = options
                values[name] = session.values[name] = [only] if is_list(info) else only
        return values

    @staticmethod
    def _consented(session: FormFillSession, name: str, page_index: int) -> bool:
        """Whether this page has the caller's ``ACCEPTED`` for this field.

        Consent given earlier for this page holds through a re-walk; a fresh ``ACCEPTED`` is for the page
        being asked now and is consumed by it, never carried to a later page that asks the same thing.
        """
        if session.accepted.get(name) == page_index:
            return True
        if session.values.get(name) == ACCEPT_VALUE:
            session.accepted[name] = page_index
            session.values.pop(name, None)
            return True
        return False

    @staticmethod
    def _create_args(session: FormFillSession) -> dict[str, Any]:
        """The ``create_workflow`` call: what the human approves is exactly what is sent."""
        return {WORKFLOW_KEY_PARAM: session.workflow_key, JSON_DATA_PARAM: session.page_inputs}

    def _summary(self, session: FormFillSession) -> Reply:
        """Every value to be submitted and the defaults that apply, for the caller to confirm."""
        given = {name: value for page in session.page_inputs for name, value in page.items()}
        defaults = {
            name: info.default
            for name, info in form_model(session.pages).model_fields.items()
            if name not in given and not info.is_required()
        }
        return as_reply(
            FormReply(workflow_key=session.workflow_key, status="confirming", values=given, defaults=defaults)
        )

    async def _start(self, session: FormFillSession, call_tool: CallTool) -> Reply:
        try:
            result = await call_tool(CREATE_WORKFLOW_TOOL, self._create_args(session))
        except ModelRetry as exc:  # core refused: correct and confirm again
            session.status = "gathering"
            given = {name: value for page in session.page_inputs for name, value in page.items()}
            return self._gathering(session, form_model(session.pages), given, str(exc))
        except Exception as exc:
            # Whether core started the process is unknown, so the form closes: never retry a start blindly.
            logger.exception("Form-fill: create_workflow failed", workflow=session.workflow_key)
            session.status = "done"
            return self._reply(session, "failed", reason=str(exc) or type(exc).__name__)
        session.status = "done"
        return self._reply(session, "started", process_id=str(ProcessIdSchema.model_validate(result).id))


