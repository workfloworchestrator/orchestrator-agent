"""The workflow form-fill skill: a deterministic walk over core's form, answered by a human in the loop.

A form is filled through a human-in-the-loop transport only (kagent's extension over A2A, or LibreChat's
ask-user tool over chat completions): every stop of the skill is a pause that shows the human the page's
questions with their options, or the start to approve, and only their structured response continues the form. No chat text is read for a value or a
decision, by this code or by a model. *Which* workflow a request asks for is the model's call: it hands
off with the ``start_workflow_form`` tool (``handoff``, which checks the key against core's catalogue)
and ``open`` walks the first pages in the same turn. Core's own validation is the only validation. One
skill turn is one response of the human:

- opening (just handed off): the form is **walked** from page 0 with the subscription the model passed
  on; a subscription core will not run the workflow on is rejected by core's own subscription page, like
  any other value.
- gathering: the answers are recorded, then the form is walked again from page 0, each page submitted
  to core as it is known; the walk stops at the first page core does not accept — its fields are the
  questions, with core's message on the ones it rejected — or at the summary. Where core rejects what a
  person typed for a field, an ``Interpreter`` turns the words into the field's value once, then core
  decides again.
- confirming: the start is the human's approval of the ``create_workflow`` call (exactly the last walk's
  validated pages); a rejection cancels. A start is sent once: only core's own verdict on the pages
  reopens the form, any other failure closes it.

A message that carries no response means the pending stop went unanswered: the form is over and the
message is the model's. The one exception is a stop that has not been shown yet (``unseen``): a parent
runtime pauses once per call, so the stop that answers a response only reaches the human when the
parent calls again, and that call shows it.

Core describes each page as data (``get_workflow_form`` with ``include_schema=false``: its ``fields``, and
with ``verdict="result"`` a rejected page as a result with its ``errors``), and everything here reads that
data as it is. Re-walking from page 0 every turn is what makes corrections free (pages after a changed
answer are regenerated by core) and keeps the session tiny; each page costs one MCP call. Routing by a
typed decision engine in front of the model, and prefilling pages from the conversation, live on the Jev
branch.
"""

